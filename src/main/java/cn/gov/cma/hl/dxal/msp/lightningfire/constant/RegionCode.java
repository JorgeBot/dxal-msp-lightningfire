    /**
     * 省级区划码。
     */
    private static final int PROVINCE_CODE = 230000;

    /**
     * 地市码对 100 取余为 0，县区码末两位非 0。
     */
    private static final int MODULUS = 100;

    /**
     * 行政区划代码（6 位）
     */
    private final int code;

    /**
     * 行政区划名称
     */
    private final String label;

    RegionCode(int code, String label) {
        this.code = code;
        this.label = label;
    }

    /**
     * 按 6 位行政区划码反查枚举。
     *
     * <p>接口上的 regionCode 参数与各汇总表的 region_code 列都是 6 位区划码，而服务层按地区名过滤、
     * 按区划范围判断下拉内容，需要的是本枚举（{@link #getLabel()} / {@link #inScope(Integer)}），
     * 两者之间的转换统一走本方法，避免各处各写一套「码 → 名」对照。</p>
     *
     * @param code 6 位行政区划码，如 232701；为 null 时返回 null
     * @return 对应枚举；枚举之外的区划码返回 null
     */
    public static RegionCode fromCode(Integer code) {
        if (code == null) {
            return null;
        }
        for (RegionCode region : values()) {
            if (region.code == code) {
                return region;
            }
        }
        return null;
    }

    /**
     * 是否为县区：既不是省，也不是地市。
     */
    public boolean isCounty() {
        return code != PROVINCE_CODE && code % MODULUS != 0;
    }

    /**
     * 是否落在所选区划码范围内，只有县区参与下拉。
     *
     * <ul>
     *   <li>code 为空或 230000（全省）：全部县区。</li>
     *   <li>code 为地市码（如 232700）：该地市所辖县区，即区划码落在 [地市码, 地市码+100) 内的县区。</li>
     *   <li>code 为县区码（如 232764）：该县区本身，便于下拉框回显当前选中项。</li>
     *   <li>其余 code（无对应县区）：不入选。</li>
     * </ul>
     */
    public boolean inScope(Integer scope) {
        if (!isCounty()) {
            return false;
        }
        if (scope == null || scope == PROVINCE_CODE) {
            return true;
        }
        if (scope % MODULUS == 0) {
            return code >= scope && code < scope + MODULUS;
        }
        return code == scope;
    }

    /**
     * 指定范围内可选的区域，即区划下拉的全部内容。
     *
     * <p>取「落在范围内的区划」并保持枚举声明顺序（省 → 地市 → 县区），是「哪些区划可选」的唯一入口；
     * 调用方不必自己遍历 {@code values()} 再过滤，以免这条规则散落到各个控制器里各写一遍。</p>
     *
     * @param scope 限定范围，语义同 {@link #inScope(Integer)}
     * @return 可选区域列表，无匹配时为空列表
     */
    public static List<RegionCode> selectable(Integer scope) {
        return Arrays.stream(values())
                .filter(region -> region.inScope(scope))
                .toList();
    }
